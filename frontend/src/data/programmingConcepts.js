const languageNames = {
  py: 'python',
  python3: 'python',
  js: 'javascript',
  node: 'javascript',
  javascript: 'javascript',
  c: 'c',
}

export function getConceptIdsForTask(task) {
  if (Array.isArray(task.conceptIds) && task.conceptIds.length > 0) return task.conceptIds

  const language = languageNames[task.language] || task.language
  const questionKey = `${language}:${task.category}`
  const title = task.title?.trim().toLowerCase()

  if (language === 'python' && title === 'greet the learner') {
    return questionConcepts['python:python-basics'][2]
  }

  const questionSpecific = questionConcepts[questionKey]?.[task.questionOrder]
  if (questionSpecific) return questionSpecific

  const matchedIds = (taskConceptRules[language] || [])
    .filter(({ pattern }) => pattern.test(title || ''))
    .flatMap(({ ids }) => ids)
  if (matchedIds.length > 0) {
    const categoryIds = conceptsByCategory[language]?.[task.category] || []
    return [...new Set([...matchedIds, ...categoryIds])].slice(0, 5)
  }

  return conceptsByCategory[language]?.[task.category] || ['problem-solving']
}

export function getConceptsForTask(task) {
  const resolved = getConceptIdsForTask(task)
    .map((id) => conceptsById.get(id))
    .filter(Boolean)

  return resolved.length > 0 ? resolved : [conceptsById.get('problem-solving')]
}

export function getLanguageLabel(language) {
  const normalized = languageNames[language] || language
  if (normalized === 'javascript') return 'JavaScript'
  if (normalized === 'python') return 'Python'
  if (normalized === 'c') return 'C'
  return normalized ? `${normalized[0].toUpperCase()}${normalized.slice(1)}` : 'Code'
}
